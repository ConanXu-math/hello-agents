"""
完整的执行顺序演示
展示从文件开头到结尾，Python 如何一步一步执行
"""

print("=" * 70)
print("【执行顺序详解】")
print("=" * 70)

print("\n步骤 1-2: 定义装饰器和函数")
print("-" * 70)

def my_decorator(func):
    print(f"    ⚡ 装饰器执行中... (装饰函数: {func.__name__})")
    return func

print("    ✅ 装饰器定义完成")

@my_decorator
def my_function():
    print("    函数内部代码执行")

print("    ✅ 函数定义完成（装饰器已执行）")

print("\n步骤 3: 继续执行文件的其他代码")
print("-" * 70)
print("    ✅ Python 继续往下执行...")
print("    ✅ 执行到 if __name__ == '__main__' 时...")

print("\n步骤 4: 执行主程序（if __name__ == '__main__'）")
print("-" * 70)

if __name__ == "__main__":
    print("    📍 现在才进入主程序")
    print("    📍 准备调用函数...")
    
    my_function()  # 现在才真正调用函数

print("\n" + "=" * 70)
print("【总结：完整的时间线】")
print("=" * 70)
print("""
时间线：
  1️⃣  文件开始 → 定义装饰器函数（只定义，不执行）
  2️⃣  遇到 @装饰器 → 立即执行装饰器（函数定义时）
  3️⃣  继续往下执行 → 执行文件的其他代码
  4️⃣  遇到 if __name__ == '__main__' → 执行主程序
  5️⃣  调用函数 → 函数内部的代码才真正执行

关键：
  ✅ 装饰器在函数定义时执行（步骤2）
  ✅ 主程序在函数定义完成后执行（步骤4）
  ✅ 函数内部的代码在函数调用时执行（步骤5）
""")
